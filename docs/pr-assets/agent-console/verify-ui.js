async (page) => {
  const origin = new URL(page.url()).origin;
  const results = {layouts: [], assertions: {}, apiRequests: [], pageErrors: []};
  const check = (value, name) => {results.assertions[name] = Boolean(value); if (!value) throw Error(name);};
  const onError = e => results.pageErrors.push(e.message);
  const onRequest = r => {if (new URL(r.url()).pathname.startsWith('/api/')) results.apiRequests.push(r.url());};
  page.on('pageerror', onError); page.on('request', onRequest);
  const tabs = ['overview','usage','jobs','knowledge','imports','sources','review','query','lint','agents','integrations','users','access','policies','lifecycle','activity','evaluation','coverage'];
  for (const width of [1440,390]) {
    await page.setViewportSize({width,height:1000});
    for (const tab of tabs) {
      await page.goto(origin+'/?preview=1&verify='+tab+'-'+width+'#'+tab);
      await page.locator('main h1').waitFor(); await page.locator('main section').first().waitFor();
      if(tab==='overview') await page.locator('.console-chart-day').first().waitFor();
      if(tab==='usage') await page.locator('.usage-report').waitFor();
      const m = await page.evaluate(() => ({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight,headingTop:document.querySelector('main h1').getBoundingClientRect().top,verdictTop:document.querySelector('.console-verdict')?.getBoundingClientRect().top??null,tableWidth:document.querySelector('.op-table-scroll table')?.getBoundingClientRect().width??null,chartFont:document.querySelector('.console-chart-day')?getComputedStyle(document.querySelector('.console-chart-day')).fontSize:null}));
      results.layouts.push({tab,...m}); check(m.scrollWidth <= width, 'no-document-overflow-'+width+'-'+tab);
      if(['overview','users','agents','access','coverage'].includes(tab)) await page.screenshot({path:'docs/pr-assets/agent-console/'+(width===1440?'desktop':'mobile')+'-'+tab+'.png',fullPage:true});
    }
  }
  await page.goto(origin+'/?preview=1&verify=interactions#users'); await page.locator('main section').first().waitFor();
  await page.getByRole('button',{name:'구성원 초대',exact:true}).click();
  await page.getByLabel('표시 이름').fill('테스트 초대'); await page.getByLabel('합성 이메일').fill('invite@example.test');
  await page.getByRole('button',{name:'초대 대기 만들기',exact:true}).click();
  check(await page.getByRole('row').filter({hasText:'invite@example.test'}).getByText('초대 대기',{exact:true}).isVisible(),'invitation-pending-not-active');
  await page.getByRole('button',{name:'김하늘 상세',exact:true}).click();
  await page.getByRole('button',{name:'중지 예시',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'목업에서 확인',exact:true}).click();
  check((await page.getByRole('dialog').getByRole('alert').innerText()).includes('마지막 Owner'),'last-owner-refused');
  await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).focus(); await page.keyboard.press('Tab');
  check(await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)),'dialog-traps-keyboard-focus');
  await page.keyboard.press('Escape'); check(await page.getByRole('dialog').count()===0,'escape-closes-dialog');
  check(await page.getByRole('button',{name:'중지 예시',exact:true}).evaluate(el=>el===document.activeElement),'dialog-restores-focus');
  await page.evaluate(()=>location.hash='agents'); await page.getByRole('heading',{name:'범위가 제한된 자격증명'}).waitFor();
  await page.getByRole('button',{name:'범위 토큰 예시',exact:true}).click();
  await page.getByLabel('토큰 이름').fill('reader-test'); await page.getByRole('dialog').getByRole('button',{name:'목업에서 확인',exact:true}).click();
  check(await page.getByText('reader-test',{exact:true}).isVisible(),'credential-metadata-only');
  await page.evaluate(()=>location.hash='users'); await page.getByRole('heading',{name:'사람과 책임 주체'}).waitFor();
  check(await page.getByText('invite@example.test',{exact:true}).isVisible(),'preview-state-survives-navigation');
  await page.reload(); await page.getByRole('heading',{name:'사람과 책임 주체'}).waitFor();
  check(await page.getByText('invite@example.test',{exact:true}).count()===0,'preview-refresh-resets-state');
  await page.getByRole('button',{name:/메뉴 ·/}).click();
  await page.locator('a[href="#coverage"]').focus(); await page.keyboard.press('Enter');
  await page.getByRole('heading',{name:'전체 기능 점검표'}).waitFor();
  check(await page.locator('nav').isHidden(),'mobile-navigation-closes-on-enter');
  check(await page.locator('main').evaluate(el=>el===document.activeElement),'navigation-focuses-main');
  await page.goBack(); await page.getByRole('heading',{name:'사람과 책임 주체'}).waitFor();
  check(page.url().endsWith('#users'),'browser-back-restores-route');
  await page.goForward(); await page.getByRole('heading',{name:'전체 기능 점검표'}).waitFor();
  check(page.url().endsWith('#coverage'),'browser-forward-restores-route');
  check(await page.locator('.op-table-scroll tbody tr').count()===25,'coverage-pages-25-of-251');
  await page.getByRole('button',{name:'다음 25건',exact:true}).click();
  check(await page.getByText('ACL-005',{exact:true}).isVisible(),'coverage-next-page-preserves-rows');
  await page.getByRole('searchbox',{name:'전체 제품 요구사항 검색'}).fill('CORE-012');
  check(await page.locator('.op-table-scroll tbody tr').count()===1,'coverage-search-all-pages');
  await page.locator('.op-table-scroll').focus(); await page.keyboard.press('ArrowRight');
  await page.waitForFunction(()=>document.querySelector('.op-table-scroll').scrollLeft>0);
  check(await page.locator('.op-table-scroll').evaluate(el=>el.scrollLeft>0),'table-keyboard-horizontal-scroll');
  await page.locator('.op-skip').focus(); await page.keyboard.press('Enter');
  check(page.url().endsWith('#coverage'),'skip-link-keeps-current-route');
  await page.getByRole('button',{name:'다크 테마',exact:true}).click();
  check(await page.evaluate(()=>document.documentElement.dataset.theme==='dark'),'dark-theme');
  await page.screenshot({path:'docs/pr-assets/agent-console/mobile-dark-coverage.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>location.hash='overview'); await page.locator('.console-chart-day').first().waitFor();
  await page.screenshot({path:'docs/pr-assets/agent-console/desktop-dark-overview.png',fullPage:true});
  await page.getByRole('button',{name:'라이트 테마',exact:true}).click();
  await page.evaluate(()=>location.hash='imports'); await page.getByRole('button',{name:'합성 대화 채우기'}).click();
  await page.getByRole('button',{name:'입력 구조 미리보기'}).click();
  check(await page.getByText('원문 진술 · 검증 전',{exact:true}).count()===3,'paste-claims-not-execution-evidence');
  await page.getByRole('checkbox').check(); await page.getByRole('button',{name:'목업 원본 등록 · 편입 화면으로'}).click();
  await page.getByRole('heading',{name:'접근 가능한 원본'}).waitFor();
  check(await page.getByText('합성 대화 자료',{exact:true}).isVisible(),'paste-registers-only-preview-source');
  await page.evaluate(()=>location.hash='review'); await page.getByRole('button',{name:'승인',exact:true}).click();
  await page.getByRole('button',{name:'승인 집합 발행',exact:true}).click();
  check(await page.getByText('발행됨',{exact:true}).isVisible(),'preview-review-and-publication');
  await page.evaluate(()=>location.hash='query'); await page.getByLabel('질문',{exact:true}).fill('컨테이너');
  await page.getByRole('button',{name:'발행 지식에 질문'}).click();
  await page.getByRole('heading',{name:'답변과 근거',exact:true}).waitFor();
  await page.getByRole('button',{name:'인용 버전 열기'}).first().click();
  check(await page.getByRole('button',{name:'인용 본문 닫기'}).isVisible(),'fixed-citation-version');
  await page.getByRole('button',{name:'답변을 위키에 재편입 제안'}).click();
  check(page.url().endsWith('#review'),'answer-refiles-as-review-proposal');
  await page.evaluate(()=>location.hash='lint'); await page.getByRole('button',{name:'서버 위키 점검'}).click();
  check((await page.locator('main').innerText()).includes('개 점검 항목'),'lint-explicit-run');
  check(results.apiRequests.length===0,'preview-api-network-zero');
  check(results.pageErrors.length===0,'preview-page-errors-zero');
  page.off('pageerror',onError); page.off('request',onRequest);
  await page.evaluate(data=>{window.__consoleVerification=data;},results);
  return {screens:results.layouts.length,assertions:Object.keys(results.assertions).length,allPassed:Object.values(results.assertions).every(Boolean),apiRequests:results.apiRequests,pageErrors:results.pageErrors,overviewLayouts:results.layouts.filter(x=>x.tab==='overview')};
}

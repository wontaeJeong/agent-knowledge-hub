import {afterEach,beforeEach,expect,test} from "vitest";
import {fixture} from "./test-support";
import {authenticateAgentKey,handleCredentialRequest,startDevice,pollDevice,verifyDevice,decideDevice,permittedAgentRoute} from "./agent-credentials";
let f:Awaited<ReturnType<typeof fixture>>;
const original=process.env.AGENT_KNOWLEDGE_HUB_AGENT_CREDENTIALS_ENABLED;
beforeEach(async()=>{process.env.AGENT_KNOWLEDGE_HUB_AGENT_CREDENTIALS_ENABLED="true";f=await fixture();});
afterEach(async()=>{await f.pool.end();if(original===undefined)delete process.env.AGENT_KNOWLEDGE_HUB_AGENT_CREDENTIALS_ENABLED;else process.env.AGENT_KNOWLEDGE_HUB_AGENT_CREDENTIALS_ENABLED=original;});
async function issue(ctx:typeof f.ctx,scope:"read"|"write"="read"){
 const result=await handleCredentialRequest(f.pool,ctx,"POST","/api/v1/credentials/keys",{name:"CI integration",scope,days:90},"http://localhost");
 expect(result?.status).toBe(201);
 return result?.body as {token:string;id:string};
}
test("API keys are opaque, once-only, owner+workspace scoped and revocable",async()=>{
 const a=await issue(f.editor,"read");
 const b=await issue(f.ctx,"write");
 expect(a.token).toMatch(/^akh_sk_[A-Za-z0-9_-]{43}$/);
 const stored=await f.pool.query("SELECT token_hash FROM agent_api_keys WHERE id=$1",[a.id]);
 expect(stored.rows[0].token_hash).not.toContain(a.token);
 const keys=await handleCredentialRequest(f.pool,f.editor,"GET","/api/v1/credentials/keys",undefined,"");
 const serialized=JSON.stringify(keys);
 expect(serialized).toContain(a.id);
 expect(serialized).not.toContain(b.id);
 expect(serialized).not.toContain(a.token);
 const actor=await authenticateAgentKey(f.pool,a.token);
 expect(actor?.workspaceId).toBe(f.workspaceId);
 expect(actor?.principalId).toBe("editor");
 expect(actor?.agent.scope).toBe("read");
 expect(permittedAgentRoute("GET","/api/v1/pages","read",undefined)).toBe(true);
 expect(permittedAgentRoute("POST","/api/v1/query","read",{})).toBe(false);
 expect(permittedAgentRoute("POST","/api/v1/changesets/x/approve","write",{})).toBe(false);
 expect(permittedAgentRoute("POST","/mcp","read",{method:"tools/call",params:{name:"knowledge_import_text"}})).toBe(false);
 await handleCredentialRequest(f.pool,f.editor,"POST","/api/v1/credentials/keys/"+a.id+"/revoke",{reason:"rotate key"},"");
 expect(await authenticateAgentKey(f.pool,a.token)).toBeNull();
 expect(await authenticateAgentKey(f.pool,b.token)).not.toBeNull();
});
test("device flow needs human confirmation, respects poll interval and consumes token once",async()=>{
 const r=await handleCredentialRequest(f.pool,f.editor,"POST","/api/v1/credentials/clients",{name:"Mac mini"},"http://localhost");
 const clientId=(r?.body as {id:string}).id;
 const start=await startDevice(f.pool,{clientId,scope:"write"},"https://wiki.example");
 const device=start.body as {deviceCode:string;userCode:string;expiresIn:number;interval:number;verificationUri:string};
 expect(device.userCode).toHaveLength(8);
 expect(device.expiresIn).toBe(600);expect(device.interval).toBe(5);
 expect(device.verificationUri).toContain("#agents");
 const pending=await pollDevice(f.pool,{deviceCode:device.deviceCode});
 expect(pending.status).toBe(202);
 await expect(pollDevice(f.pool,{deviceCode:device.deviceCode})).rejects.toThrow("SLOW_DOWN");
 await expect(verifyDevice(f.pool,f.reader,device.userCode)).rejects.toThrow("NOT_FOUND");
 const detail=await verifyDevice(f.pool,f.editor,device.userCode);
 expect(detail.body).toMatchObject({requested_scope:"write",clientName:"Mac mini"});
 await decideDevice(f.pool,f.editor,{userCode:device.userCode,approve:true});
 await f.pool.query("UPDATE agent_device_grants SET last_poll_at=clock_timestamp()-interval '6 seconds' WHERE user_code=$1",[device.userCode]);
 const issued=await pollDevice(f.pool,{deviceCode:device.deviceCode});
 expect(issued.status).toBe(200);
 const key=(issued.body as {access_token:string}).access_token;
 expect(key).toMatch(/^akh_sk_/);
 await expect(pollDevice(f.pool,{deviceCode:device.deviceCode})).rejects.toThrow("INVALID_GRANT");
 expect(await authenticateAgentKey(f.pool,key)).not.toBeNull();
 await handleCredentialRequest(f.pool,f.editor,"DELETE","/api/v1/credentials/clients/"+clientId,{},"");
 expect(await authenticateAgentKey(f.pool,key)).toBeNull();
});
test("denied device grant cannot be exchanged, and membership removal revokes machine access",async()=>{
 const client=await handleCredentialRequest(f.pool,f.editor,"POST","/api/v1/credentials/clients",{name:"test"},"");
 const id=(client?.body as {id:string}).id;
 const start=await startDevice(f.pool,{clientId:id,scope:"read"},"https://example");
 const d=start.body as {userCode:string;deviceCode:string};
 await decideDevice(f.pool,f.editor,{userCode:d.userCode,approve:false});
 await expect(pollDevice(f.pool,{deviceCode:d.deviceCode})).rejects.toThrow("ACCESS_DENIED");
 const key=await issue(f.editor);
 await f.pool.query("DELETE FROM resource_readers WHERE workspace_id=$1 AND principal_id=$2",[f.workspaceId,"editor"]);
 await f.pool.query("DELETE FROM memberships WHERE workspace_id=$1 AND principal_id=$2",[f.workspaceId,"editor"]);
 expect(await authenticateAgentKey(f.pool,key.token)).toBeNull();
});
